      LeakageWeakestPrecondition.call functions
        "stackdisj" k t m [] (fun k' t' m' rets => exists a b, rets = [a;b] /\ a <> b /\ m'=m/\t'=t).

  Lemma stackdisj_ok : program_logic_goal_for_function! stackdisj.
  Proof.
    repeat straightline.
    set (R := eq m).
    pose proof (eq_refl : R m) as Hm.
    repeat straightline.
    repeat esplit.
    all : try intuition congruence.
    match goal with |- _ <> _ => idtac end.
  Abort.

  Instance spec_of_stackswap : spec_of "stackswap" :=
    fnspec! exists f, "stackswap" a b ~> B A,
    { requires k t m := True ;
      ensures k' t' m' := k' = f k ++ k }.

  Require Import bedrock2Examples.swap.

  Lemma stackswap_ok :
    let swapspec := spec_of_swap in
    program_logic_goal_for_function! stackswap.
  Proof.
    repeat straightline.
    set (R := eq m).
    pose proof (eq_refl : R m) as Hm.
    repeat straightline.
    seprewrite_in_by @scalar_of_list_word_at Hm ltac:(cbv [bytes_per bytes_per_word]; cbn; Lia.lia).
    repeat straightline.
    seprewrite_in_by @scalar_of_list_word_at H1 ltac:(cbv [bytes_per bytes_per_word]; cbn; Lia.lia).
    repeat straightline.
    straightline_call.
    { ecancel_assumption. }
    repeat straightline. align_trace.
  Qed.
End WithParameters.

