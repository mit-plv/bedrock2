  Instance spec_of_stacktrivial : spec_of "stacktrivial" :=
    fun functions =>
      forall k t m, LeakageWeakestPrecondition.call functions
                 "stacktrivial" k t m [] (fun k' t' m' rets => rets = [] /\ m'=m /\ t'=t).

  Lemma stacktrivial_ok : program_logic_goal_for_function! stacktrivial.
  Proof.
    repeat straightline.

    set (R := eq m).
    pose proof (eq_refl : R m) as Hm.

    repeat straightline.

    (* test for presence of intermediate separation logic hypothesis generated by [straightline_stackalloc] *)
    lazymatch goal with H : Z.of_nat (Datatypes.length ?stackarray) = 4 |- _ =>
    lazymatch goal with H : sep _ _ _ |- _ =>
    lazymatch type of H with context [map.of_list_word_at ?a stackarray] =>
    idtac
    end end end.

    intuition congruence.
  Qed.

  Instance spec_of_stacknondet : spec_of "stacknondet" := fun functions => forall m t k,
      LeakageWeakestPrecondition.call functions
        "stacknondet" k t m [] (fun k' t' m' rets => exists a b, rets = [a;b] /\ a = b /\ m'=m/\t'=t).

  Lemma stacknondet_ok : program_logic_goal_for_function! stacknondet.
  Proof.
    repeat straightline.
    set (R := eq m).
    pose proof (eq_refl : R m) as Hm.
    repeat straightline.
    repeat (destruct stack as [|?b stack]; try solve [cbn in length_stack; Lia.lia]; []).
    seprewrite_in_by @scalar32_of_list_word_at Hm reflexivity.
    repeat straightline.
    Import symmetry.
    seprewrite_in_by (symmetry! @scalar32_of_list_word_at) Hm reflexivity.
    seprewrite_in_by @Array.sep_eq_of_list_word_at_cons Hm ltac:(cbn [length]; Lia.lia).
    repeat straightline.
    match goal with H : sep (ptsto _ _) _ _ |- _ =>
      seprewrite_in_by (symmetry! @Array.sep_eq_of_list_word_at_cons) H ltac:(cbn [length]; Lia.lia);
      seprewrite_in_by @scalar32_of_list_word_at H reflexivity
    end.
    repeat straightline.
    Tactics.ssplit; eauto.

    subst v. subst v1.
    eapply Zmod.unsigned_inj.
    rewrite ?shamt_of_Z_small by Lia.lia.
    rewrite ?Zmod.unsigned_sru by Lia.lia.
    rewrite ?bits.unsigned_of_Z_small; try Lia.lia.
    2,3: eapply (LittleEndianList.le_combine_bound [_;_;_;_]).
    repeat change [?a;?b;?c;?d] with ([a]++[b;c;d]).
    rewrite 2LittleEndianList.le_combine_app, 2LittleEndianList.le_combine_1, 2Z.shiftr_lor; simpl Z.of_nat; f_equal.
    rewrite 2Z.shiftr_div_pow2, 2Zdiv.Zdiv_small; eauto using Byte.byte.unsigned_range; Lia.lia.
  Qed.

